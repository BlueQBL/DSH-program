export const DEFAULT_PERSONA_ID = 'default';
export const CUSTOM_PERSONA_ID = 'custom';

/** 提示词长度上限：足够写详细设定，又不会把上下文撑爆 */
export const MAX_PROMPT_CHARS = 4000;

export function getPersona(id) {
  return PERSONAS.find((p) => p.id === id) ?? PERSONAS[0];
}

/**
 * 解析某个会话最终要发给模型的系统提示词。
 *
 * 三种情况：
 *  · 选了自定义 → 用用户手写的那段
 *  · 选了内置角色 → 用角色预设；若用户又改过，以用户改的为准
 *  · 没选 → 返回空，服务端用自己的默认提示词
 */
export function resolveSystemPrompt(personaId, customPrompt) {
  const own = typeof customPrompt === 'string' ? customPrompt.trim().slice(0, MAX_PROMPT_CHARS) : '';
  if (personaId === CUSTOM_PERSONA_ID) return own;
  if (own) return own;
  return getPersona(personaId).prompt;
}

/** 会话列表里显示的角色名 */
export function personaLabel(personaId) {
  return getPersona(personaId).name;
}
